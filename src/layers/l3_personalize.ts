/** 社名から法人格を落として業種語だけを残す。 */
function coreName(name: string): string {
  return name
    .replace(/株式会社|有限会社|合同会社|合資会社|合名会社|一般社団法人|一般財団法人|公益社団法人|公益財団法人|医療法人(?:社団|財団)?|社会福祉法人|学校法人|宗教法人|（株）|\(株\)|（有）|\(有\)/g, '')
    .trim();
}

/** 社名＋ドメインから業種を推定する（該当なしなら null）。 */
export function inferIndustry(company: Pick<CompanyRow, 'name' | 'domain'>): IndustryRule | null {
  const hay = `${coreName(company.name)} ${company.domain ?? ''}`;
  return INDUSTRY_RULES.find((r) => r.keywords.test(hay)) ?? null;
}

/**
 * 「なぜ御社にご連絡したのか」の段落を組み立てる。業種が推定できなければ、
 * 業種に触れない汎用版を返す（推測を断定として書かないため）。
 */
export function personalize(company: CompanyRow): Personalization {
  const rule = inferIndustry(company);
  const name = company.name;

  if (!rule) {
    return {
      industry: '',
      reason:
        `${name}様の採用情報を拝見し、新卒採用に継続して取り組まれていると存じ、ご連絡いたしました。\n` +
        '新卒採用では、応募をいただいたあとの日程調整や連絡のやり取りに工数がかかり、\n' +
        '連絡が滞ることが辞退につながる、というご相談を多くいただいております。',
    };
  }

  // 業種課題の一文は最も長い（〜130字）。本文が textarea の maxlength に収まらない
  // ときに落とせるよう optional:2 で囲む。囲みは L3 の縮約処理が解釈する
  // (l3_content の fitOptional)。落ちても「なぜ御社か」の一文目は必ず残る。
  return {
    industry: rule.industry,
    reason:
      `${name}様の事業内容を拝見し、${rule.industry}分野で新卒採用に取り組まれていると存じ、ご連絡いたしました。\n` +
      `<!--optional:2-->\n` +
      `${rule.industry}の企業様からは、${rule.pain}に課題を感じている、というお声を多くいただいております。\n` +
      `<!--/optional-->\n` +
      `${name}様でも近しい状況がございましたら、お役に立てるのではないかと考えております。`,
  };
}
